// 确定性伪随机 —— 五个**模拟**模块的数值都由它生成。
//
// ★ 这个文件原来是 `blocks.js`，里面还装着一张 15 个假体块的表
//   （`M-01 图书馆` / `M-02 教学主楼` …）与它们的多边形布局。那张表是
//   2026-10-01 之前"三维场景"用的，而它同时也是「10 个模块 = 10 张互不
//   相干的页面」那个诊断的一半证据：**屏幕上的楼名与真名册零映射**。
//   2026-10-02 「一个世界」重做把轮廓换成 341 条实测轮廓（见 `world/outlines.js`），
//   那张表就再没有调用方了 ⇒ 删掉，只留下**还有人在用**的这一半。
//   ★ 删除的依据是「没有调用方」，不是"我看着像没用了"。
//
// ★ 下面这两个函数**照抄原样，一个字节没改** —— 五个模块的模拟数是按
//   这两个函数**逐位复现**出来的，换一种 PRNG 会让它们全变一遍，
//   而"换了一批数"与"换了一个实现"在屏幕上长得一样。
//
// ★ 为什么不用 `Math.random()`：模拟台账每次刷新都要给出**同一组数**。
//   随机的话，"3 号楼有 12 部电梯"这句话在你第二次打开时变成 9 部，
//   而没有任何东西会提醒你它是编的 —— 一个会自己变的数，
//   看起来比一个固定的数更"真"。

/** FNV-1a —— 把块 id 变成一个种子。 */
function hash32(s) {
  let h = 2166136261 >>> 0;
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return h >>> 0;
}

/** mulberry32。种子是字符串本身 ⇒ 换机器、换浏览器、换时间，同一 id 得同一组数。 */
export function rng(seedStr) {
  let a = hash32(seedStr);
  return () => {
    a = (a + 0x6D2B79F5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
