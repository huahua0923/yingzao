def _lines(g):
    """多边形/多线/环 → 折线列表（`_ivs` 与 `_seg_list` 共用的拆解）。"""
    if g is None or g.is_empty:
        return []
    if g.geom_type == "LineString":
        return [g]
    if g.geom_type == "LinearRing":
        return [sg.LineString(g.coords)]
    out = []
    for x in getattr(g, "geoms", []):
        out.extend(_lines(x))
    return out


def _seg_list(walls):
    """墙带的边（**外环 + 内环**）按长度登记，供「在 Q 附近挑墙向」用。

    ★ 内环**必须一起收**：`wall_polys` 是栅格掩膜的轮廓，**房间就是内环**，
      门洞两侧的墙面大多落在内环上 —— 只收外环会把大部分门判成「方向不可信」。
    """
    out = []
    for w in walls:
        for ring in [w.exterior] + list(w.interiors):
            p = list(ring.coords)
            for a, b in zip(p, p[1:]):
                L = math.hypot(b[0] - a[0], b[1] - a[1])
                if L >= 50.0:
                    out.append((sg.LineString([a, b]), L,
                                math.atan2(b[1] - a[1], b[0] - a[0])))
    return out


def _merge(ivs):
    ivs = sorted(ivs)
    m = []
    for a, b in ivs:
        if a > b:
            continue
        if m and a <= m[-1][1] + 0.5:
            m[-1] = (m[-1][0], max(m[-1][1], b))
        else:
            m.append((a, b))
    return m


def _sub(ivs, hole):
    a, b = hole
    out = []
    for x, y in ivs:
        if b <= x + 0.5 or a >= y - 0.5:
            out.append((x, y))
            continue
        if x < a - 0.5:
            out.append((x, min(y, a)))
        if y > b + 0.5:
            out.append((max(x, b), y))
    return out


def _ivs(geom, O, dx, dy):
    """几何的**边**沿 (dx,dy) 的投影区间（单条扫线用；区域投影见 `_proj_ivs`）。"""
    ivs = []
    for g in _lines(geom):
        ts = [(c[0] - O[0]) * dx + (c[1] - O[1]) * dy for c in g.coords]
        if ts:
            ivs.append((min(ts), max(ts)))
    return _merge(ivs)


def _proj_ivs(geom, O, dx, dy):
    r"""**区域**沿 (dx,dy) 的投影区间 = 各外环区间之并 − 各内环区间。

    ★ 为什么不用单条扫线：墙带轮廓是**栅格掩膜**出来的，边上全是台阶；一条扫线
      贴着台阶走，只要有一处相切就把整段判成「有墙」或「无墙」。前四把尺子
      （边界点扫 / 中线扫 / 含不含 C / 门扇长轴）全栽在这个上。
      区域投影对台阶**免疫**：连通区域的投影恒是一段区间（连续集在线性映射下仍连续），
      所以逐多边形取 [min t, max t]、洞照着减即可 —— 精确，不采样。
    """
    add, sub = [], []
    for poly in polys_of(geom):
        if poly.geom_type != "Polygon":
            continue
        ts = [(c[0] - O[0]) * dx + (c[1] - O[1]) * dy for c in poly.exterior.coords]
        add.append((min(ts), max(ts)))
        for r_ in poly.interiors:
            ts2 = [(c[0] - O[0]) * dx + (c[1] - O[1]) * dy for c in r_.coords]
            sub.append((min(ts2), max(ts2)))
    ivs = _merge(add)
    for s in sub:
        ivs = _sub(ivs, s)
    return ivs


def _gaps(ivs, half):
    """`[-half, half]` 里没有墙材的那些区间（含两端伸到边界外的两段）。"""
    g, prev = [], -half
    for a, b in ivs:
        if a - prev > 1.0:
            g.append((prev, a))
        prev = max(prev, b)
    if half - prev > 1.0:
        g.append((prev, half))
    return g


