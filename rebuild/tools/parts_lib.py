        #   伸进房间（`build3d.door_polys` 的注释里已经逐块量过），**洞口不在门扇正下方，
        #   在铰链沿墙的那一侧**。缺口法在门扇处找不到自身缺口 ⇒ 归因「无界」19 扇的签名
        #   就是它挑中的缺口其实是**墙尽头以外**那一段。
        #   迈步法天然处理：从铰链迈出去，撞到远门垛为止；门扇画成关着（长轴沿墙）时，
        #   t_leaf 落在洞口正中，两侧各撞一次门垛 ⇒ 得到的是同一个洞口。
        # ★ 判「是不是墙」用**占比**不是「有没有」：窗内墙材面积 ÷ 窗面积 ≥ 0.35
        #   （三个数是量出来的：整墙 ≈ tk/(tk+50) ≈ 0.83、洞口里的门槛细线 ≈ 0.17、
        #     门垛面 = 一半 ⇒ 0.41。0.35 落在 0.17 与 0.41 之间 —— 铁律 103）。
        march = None
        march_why = "无缺口"
        if not (gap and _mk(*gap).buffer(1.0, join_style=2).intersects(lf)):
            SOL = 0.35
            stp = max(120.0, 0.5 * tk)          # 首步 = 墙厚的一半（栅格级），之后 ×1.6
